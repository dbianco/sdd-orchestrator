import type { Queryable } from '../db/pool.js';
import { hintFor } from '../gates/hints.js';
import { pendingApproval } from '../store/approvals.js';
import { requireFeature } from '../store/features.js';
import { rtmRows } from '../store/rtm.js';
import { listTransitions } from '../store/transitions.js';

export const PR_COMMENT_MARKER = '<!-- sdd-orchestrator:summary -->';

const cell = (s: string | number | null | undefined): string => String(s ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const coverage = (c: boolean | null): string => (c === null ? '⏳ pending' : c ? '✅ covered' : '❌ uncovered');

/** Markdown summary of one feature for a pull request: traceability, open blockers with fixes, pending approval. */
export async function featurePrComment(q: Queryable, featureId: string): Promise<string> {
  const feature = await requireFeature(q, featureId);
  const rows = (await rtmRows(q, feature.app_id)).filter((r) => r.feature_id === feature.id);
  const transitions = await listTransitions(q, feature.id);
  const approval = await pendingApproval(q, feature.id);
  const lastGate = [...transitions].reverse().find((t) => t.result !== 'awaiting_approval');
  const blockers = lastGate?.result === 'fail' ? lastGate.findings.filter((f) => f.severity === 'blocker') : [];

  const lines = [PR_COMMENT_MARKER, `### SDD · \`${feature.slug}\``, '',
    `**Phase:** \`${feature.current_phase}\` · **Status:** ${feature.status}${feature.blocked_reason ? ` (${cell(feature.blocked_reason)})` : ''} · **Framework:** ${feature.framework}${feature.track ? `:${feature.track}` : ''}${feature.external_ref ? ` · **Ticket:** ${cell(feature.external_ref)}` : ''}`, ''];

  if (rows.length === 0) lines.push('_No requirements captured yet._', '');
  else {
    const covered = rows.filter((r) => r.covered).length;
    lines.push(`**${covered} of ${rows.length} requirements covered by evidence.**`, '',
      '| Requirement | Coverage | Tests | Evidence | Spec approved by |', '|---|---|---|---|---|',
      ...rows.map((r) => `| ${cell(r.req_id)} | ${coverage(r.covered)} | ${r.tests_passed === null ? '—' : `${r.tests_passed} passed, ${r.tests_failed ?? 0} failed`} | ${cell(r.evidence_source)} | ${cell(r.spec_approved_by)} |`), '');
  }
  if (approval) lines.push(`⏳ **Waiting for approval** of \`${approval.from_phase}\` → \`${approval.to_phase}\` (requested by ${cell(approval.requested_by)}).`, '');
  if (blockers.length > 0) {
    lines.push(`**Blocking \`${lastGate!.from_phase}\` → \`${lastGate!.to_phase}\`:**`);
    for (const f of blockers) {
      const hint = hintFor(f.check);
      lines.push(`- \`${f.check}\`${f.location ? ` (${cell(f.location)})` : ''}: ${cell(f.message)}${hint ? `  \n  _Fix:_ ${hint.fix}` : ''}`);
    }
    lines.push('');
  }
  lines.push('<sub>Generated by SDD Orchestrator. This comment is updated on every push.</sub>');
  return `${lines.join('\n')}\n`;
}
